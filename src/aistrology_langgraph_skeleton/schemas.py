"""Pydantic schemas enforcing boundaries across the AIstrology LangGraph workflow."""

from typing import Annotated, Literal
from langchain_core.messages import AnyMessage, HumanMessage
from langgraph.graph.message import add_messages
from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# 1. Classification Boundary Schema
# ---------------------------------------------------------------------------


class Classification(BaseModel):
    """Pydantic structured output for classifying the user's question domain."""

    category: Literal["career", "relationships", "education", "health", "general"] = (
        Field(description="Defines category field of question asked by user")
    )


# ---------------------------------------------------------------------------
# 2. Research Findings Boundary Schemas (MCP / RAG Summary)
# ---------------------------------------------------------------------------


class ResearchFinding(BaseModel):
    """A validated atomic finding extracted from raw tool executions or retrieval."""

    source: str = Field(
        description="Source of the finding (e.g. 'vedic-astrology MCP server', 'rag-docs', or 'direct calculation')."
    )
    tool_name: str = Field(
        description="Name of the specific tool or retrieval source called (or 'none' if conceptual)."
    )
    facts: list[str] = Field(
        default_factory=list,
        description="Atomic, verified factual observations or calculations directly supported by the tool output.",
    )
    confidence: Literal["high", "medium", "low"] = Field(
        default="high",
        description="Confidence level in the finding based on calculation reliability and data completeness.",
    )
    uncertainty: str | None = Field(
        default=None,
        description="Known uncertainties, approximations, assumptions, or ambiguities in the data.",
    )
    limitations: list[str] = Field(
        default_factory=list,
        description="Known limitations or caveats (e.g. requires precise birth time, specific ayanamsa).",
    )


class ResearchSummary(BaseModel):
    """Validated synthesis of all research findings produced by the dedicated summary node."""

    findings: list[ResearchFinding] = Field(
        default_factory=list,
        description="Collection of validated research findings parsed from raw tool executions.",
    )
    overall_confidence: Literal["high", "medium", "low"] = Field(
        default="medium",
        description="Overall confidence in the aggregated research findings.",
    )
    summary: str = Field(
        description="Synthesized summary of all verified findings to guide the chat agent.",
    )
    limitations: list[str] = Field(
        default_factory=list,
        description="Global limitations or gaps identified across the research data.",
    )
    unresolved_questions: list[str] = Field(
        default_factory=list,
        description="Any questions, calculations, or data points that failed validation or could not be verified.",
    )


# ---------------------------------------------------------------------------
# 3. Final Answer Boundary Schema (Chat Node)
# ---------------------------------------------------------------------------


class FinalAnswer(BaseModel):
    """Structured final answer generated by the chat node."""

    concise_answer: str = Field(
        description="A direct, clear, and concise answer to the user's question based strictly on verified findings."
    )
    chart_evidence: list[str] = Field(
        default_factory=list,
        description="Astrological evidence or chart calculations supporting the answer (planets, houses, dashas, transits).",
    )
    practical_suggestions: list[str] = Field(
        default_factory=list,
        description="Actionable, grounded practical suggestions or constructive life guidance for the user.",
    )
    uncertainty_disclaimer: str = Field(
        default=(
            "Astrological interpretations reflect symbolic tendencies and potentials rather than deterministic guarantees."
        ),
        description="Uncertainty notes, boundary caveats, and ethical disclaimer.",
    )
    missing_input_request: str | None = Field(
        default=None,
        description="Request for missing birth profile details or clarifications needed for greater accuracy, or None if complete.",
    )

    def to_markdown(self) -> str:
        """Format the final answer as clean, readable Markdown for display."""
        sections = [f"### Answer\n{self.concise_answer}"]
        if self.chart_evidence:
            sections.append(
                "### Chart Evidence\n"
                + "\n".join(f"- {item}" for item in self.chart_evidence)
            )
        if self.practical_suggestions:
            sections.append(
                "### Practical Suggestions\n"
                + "\n".join(f"- {item}" for item in self.practical_suggestions)
            )
        if self.missing_input_request:
            sections.append(
                f"### Missing Inputs / Clarifications\n{self.missing_input_request}"
            )
        if self.uncertainty_disclaimer:
            sections.append(f"### Note & Disclaimer\n*{self.uncertainty_disclaimer}*")
        return "\n\n".join(sections)


# ---------------------------------------------------------------------------
# 4. LangGraph State Schema
# ---------------------------------------------------------------------------


class ChatState(BaseModel):
    """LangGraph conversation state enforcing validated schemas at every node boundary."""

    # The current user request; kept separate from tool-call messages.
    question: HumanMessage

    messages: Annotated[list[AnyMessage], add_messages] = Field(
        default_factory=list,
        description="Research-agent and tool-call messages for the current question",
    )
    category: str | None = "Unclassified"
    skill_instructions: str | None = "None"

    # Snapshot loaded from the authoritative user-profile database.
    user_id: str
    birth_profile_version: int
    dob: str
    birth_time: str
    birth_place: str

    research_findings: ResearchSummary | None = Field(
        default=None,
        description="Validated research findings and summary from MCP/RAG results",
    )
    final_answer: FinalAnswer | None = Field(
        default=None,
        description="Final structured output adhering to FinalAnswer schema",
    )

